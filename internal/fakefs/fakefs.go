// Package fakefs is an in-memory drive and object store for tests: it behaves
// like the S3 adapter where that matters (parents must exist, a source must have
// the declared size) and can fail, change or damage things on demand.
package fakefs

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"hash"
	"io"
	"path"
	"sort"
	"strings"
	"sync"
	"time"

	odraz "github.com/odrazdotxyz/odraz-go-sdk"
	"github.com/odrazdotxyz/odraz-go-sdk/files"
)

type node struct {
	dir  bool
	data []byte
	size int64
	sum  string
	gen  int64 // > 0: that many generated bytes instead of data
	rev  int
	mod  time.Time
}

// FS is the fake. The exported fields may be set between calls.
type FS struct {
	// Before is called ahead of every operation; an error from it fails the call.
	Before func(op, p string) error
	// ReadOnly refuses changes.
	ReadOnly bool
	// Discard keeps only size and checksum of what is written under /odraz.
	Discard bool
	// NoChecksum makes Check.Verify answer ErrUnsupported.
	NoChecksum bool
	// PreviewImage is returned by Preview; without it there is no preview.
	PreviewImage []byte
	// DamageWrites flips a byte of every file written whose path contains it.
	DamageWrites string
	// Short and Long make Read of a path give fewer or more bytes than Stat says.
	Short, Long map[string]bool

	mu    sync.Mutex
	nodes map[string]*node
	rev   int
	log   []string
	reads map[string]int
}

// New returns an empty drive.
func New() *FS {
	return &FS{nodes: map[string]*node{"/": {dir: true}}, reads: map[string]int{}, Short: map[string]bool{}, Long: map[string]bool{}}
}

func (f *FS) call(op, p string) error {
	f.mu.Lock()
	f.log = append(f.log, op+" "+p)
	f.mu.Unlock()
	if f.Before != nil {
		return f.Before(op, p)
	}
	return nil
}

// Log returns the operations so far, as "op path".
func (f *FS) Log() []string { f.mu.Lock(); defer f.mu.Unlock(); return append([]string(nil), f.log...) }

// Reads says how often the content of p was opened.
func (f *FS) Reads(p string) int { f.mu.Lock(); defer f.mu.Unlock(); return f.reads[p] }

// Put stores a file, creating its folders (no operation is logged).
func (f *FS) Put(p string, data []byte) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.mkdirs(path.Dir(p))
	f.put(p, append([]byte(nil), data...))
}

// PutGenerated stores a file of size bytes that are made up while read.
func (f *FS) PutGenerated(p string, size int64) {
	f.Put(p, nil)
	f.mu.Lock()
	defer f.mu.Unlock()
	f.nodes[p].gen, f.nodes[p].size = size, size
}

func (f *FS) put(p string, data []byte) {
	f.rev++
	s := sha256.Sum256(data)
	f.nodes[p] = &node{data: data, size: int64(len(data)), sum: hex.EncodeToString(s[:]), rev: f.rev, mod: time.Unix(int64(1_700_000_000+f.rev), 0).UTC()}
}

func (f *FS) mkdirs(p string) {
	for ; p != "/" && p != "."; p = path.Dir(p) {
		if f.nodes[p] == nil {
			f.nodes[p] = &node{dir: true}
		}
	}
}

// Data returns the content of a file, or nil.
func (f *FS) Data(p string) []byte {
	f.mu.Lock()
	defer f.mu.Unlock()
	if n := f.nodes[p]; n != nil && !n.dir {
		return append([]byte{}, n.data...)
	}
	return nil
}

// Files lists every file path, sorted.
func (f *FS) Files() (out []string) {
	f.mu.Lock()
	defer f.mu.Unlock()
	for p, n := range f.nodes {
		if !n.dir {
			out = append(out, p)
		}
	}
	sort.Strings(out)
	return out
}

// Has reports whether anything is at p.
func (f *FS) Has(p string) bool { f.mu.Lock(); defer f.mu.Unlock(); return f.nodes[p] != nil }

// Corrupt flips a byte of the file at p.
func (f *FS) Corrupt(p string) {
	f.mu.Lock()
	defer f.mu.Unlock()
	n := f.nodes[p]
	n.data[0] ^= 1
	s := sha256.Sum256(n.data)
	n.sum = hex.EncodeToString(s[:])
}

func (f *FS) get(op, p string) (*node, error) {
	n := f.nodes[p]
	if n == nil {
		return nil, fmt.Errorf("fakefs: %s %s: %w", op, p, odraz.ErrNotFound)
	}
	return n, nil
}

func entry(p string, n *node) files.Entry {
	e := files.Entry{Path: p, Name: path.Base(p), IsDir: n.dir, Size: n.size, ModTime: n.mod}
	if !n.dir {
		e.ETag = fmt.Sprint("e", n.rev)
	}
	return e
}

func (f *FS) Stat(ctx context.Context, p string) (files.Entry, error) {
	if err := f.guard(ctx, "stat", p); err != nil {
		return files.Entry{}, err
	}
	f.mu.Lock()
	defer f.mu.Unlock()
	n, err := f.get("stat", p)
	if err != nil {
		return files.Entry{}, err
	}
	return entry(p, n), nil
}

func (f *FS) guard(ctx context.Context, op, p string) error {
	if err := f.call(op, p); err != nil {
		return err
	}
	return ctx.Err()
}

func (f *FS) List(ctx context.Context, p string) ([]files.Entry, error) {
	if err := f.guard(ctx, "list", p); err != nil {
		return nil, err
	}
	f.mu.Lock()
	defer f.mu.Unlock()
	if _, err := f.get("list", p); err != nil {
		return nil, err
	}
	var out []files.Entry
	for q, n := range f.nodes {
		if q != "/" && path.Dir(q) == p {
			out = append(out, entry(q, n))
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	return out, nil
}

type generated struct {
	left int64
	at   int64
}

func (g *generated) Read(b []byte) (int, error) {
	if g.left == 0 {
		return 0, io.EOF
	}
	if int64(len(b)) > g.left {
		b = b[:g.left]
	}
	for i := range b {
		b[i] = byte((g.at + int64(i)) * 7)
	}
	g.at += int64(len(b))
	g.left -= int64(len(b))
	return len(b), nil
}

func (f *FS) Read(ctx context.Context, p string, off, length int64) (io.ReadCloser, error) {
	if err := f.guard(ctx, "read", p); err != nil {
		return nil, err
	}
	f.mu.Lock()
	defer f.mu.Unlock()
	n, err := f.get("read", p)
	if err != nil {
		return nil, err
	}
	if n.dir {
		return nil, fmt.Errorf("fakefs: %s: %w", p, odraz.ErrInvalidPath)
	}
	f.reads[p]++
	if n.gen > 0 {
		return io.NopCloser(&generated{left: n.gen}), nil
	}
	data := append([]byte(nil), n.data[off:]...)
	if length >= 0 && length < int64(len(data)) {
		data = data[:length]
	}
	if f.Short[p] {
		data = data[:len(data)/2]
	}
	if f.Long[p] {
		data = append(data, "extra"...)
	}
	return io.NopCloser(bytes.NewReader(data)), nil
}

func (f *FS) changeable(ctx context.Context, op, p string) error {
	if err := f.guard(ctx, op, p); err != nil {
		return err
	}
	if f.ReadOnly {
		return fmt.Errorf("fakefs: %s: %w", p, odraz.ErrPermission)
	}
	return nil
}

func (f *FS) Write(ctx context.Context, p string, r io.Reader, o files.WriteOptions) error {
	if err := f.changeable(ctx, "write", p); err != nil {
		return err
	}
	f.mu.Lock()
	old, parent := f.nodes[p], f.nodes[path.Dir(p)]
	f.mu.Unlock()
	if parent == nil || !parent.dir {
		return fmt.Errorf("fakefs: %s: parent missing: %w", p, odraz.ErrNotFound)
	}
	if old != nil && (!o.Overwrite || old.dir) {
		return fmt.Errorf("fakefs: %s: %w", p, odraz.ErrExists)
	}
	h := sha256.New()
	var buf bytes.Buffer
	var w io.Writer = io.MultiWriter(h, &buf)
	discard := f.Discard && strings.HasPrefix(p, "/odraz/")
	if discard {
		w = h
	}
	size, err := io.Copy(w, r)
	if err != nil {
		return err
	}
	if o.Size >= 0 && size != o.Size {
		return fmt.Errorf("fakefs: %s: %d bytes, declared %d: %w", p, size, o.Size, odraz.ErrInvalidPath)
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	data := buf.Bytes()
	if f.DamageWrites != "" && strings.Contains(p, f.DamageWrites) && len(data) > 0 {
		data[0] ^= 1
		h = sha256.New()
		h.Write(data)
	}
	f.mu.Lock()
	defer f.mu.Unlock()
	f.put(p, data)
	f.nodes[p].size, f.nodes[p].sum = size, hex.EncodeToString(h.Sum(nil))
	return nil
}

func (f *FS) Mkdir(ctx context.Context, p string) error {
	if err := f.changeable(ctx, "mkdir", p); err != nil {
		return err
	}
	f.mu.Lock()
	defer f.mu.Unlock()
	f.mkdirs(p)
	return nil
}

func (f *FS) Move(ctx context.Context, from, to string, _ bool) error {
	return fmt.Errorf("fakefs: move: %w", odraz.ErrUnsupported)
}

func (f *FS) children(p string) bool {
	for q := range f.nodes {
		if q != p && strings.HasPrefix(q, p+"/") {
			return true
		}
	}
	return false
}

func (f *FS) remove(ctx context.Context, op, p string, missingOK bool) error {
	if err := f.changeable(ctx, op, p); err != nil {
		return err
	}
	f.mu.Lock()
	defer f.mu.Unlock()
	if f.nodes[p] == nil {
		if missingOK {
			return nil
		}
		return fmt.Errorf("fakefs: %s %s: %w", op, p, odraz.ErrNotFound)
	}
	if f.children(p) {
		return fmt.Errorf("fakefs: %s %s: %w", op, p, odraz.ErrNotEmpty)
	}
	delete(f.nodes, p)
	return nil
}

func (f *FS) Delete(ctx context.Context, p string, _ bool) error {
	return f.remove(ctx, "delete", p, false)
}

func (f *FS) Purge(ctx context.Context, p string) error { return f.remove(ctx, "purge", p, true) }

func (f *FS) Capabilities() files.Capabilities {
	return files.Capabilities{RealDirectories: true, RangeRead: true, ReadOnly: f.ReadOnly}
}

func (f *FS) Preview(ctx context.Context, p string, _, _ int) (io.ReadCloser, string, error) {
	if err := f.guard(ctx, "preview", p); err != nil {
		return nil, "", err
	}
	if f.PreviewImage == nil {
		return nil, "", fmt.Errorf("fakefs: %w", odraz.ErrUnsupported)
	}
	return io.NopCloser(bytes.NewReader(f.PreviewImage)), "image/png", nil
}

type check struct {
	f    *FS
	size int64
	n    int64
	h    hash.Hash
}

func (c *check) Write(b []byte) (int, error) { c.n += int64(len(b)); return c.h.Write(b) }

func (c *check) Verify(ctx context.Context, p string) error {
	if err := c.f.guard(ctx, "verify", p); err != nil {
		return err
	}
	if c.f.NoChecksum {
		return fmt.Errorf("fakefs: %w", odraz.ErrUnsupported)
	}
	c.f.mu.Lock()
	defer c.f.mu.Unlock()
	n, err := c.f.get("verify", p)
	if err != nil {
		return err
	}
	if c.n != c.size || n.size != c.size || n.sum != hex.EncodeToString(c.h.Sum(nil)) {
		return fmt.Errorf("fakefs: %s: %w", p, odraz.ErrChecksum)
	}
	return nil
}

func (f *FS) NewCheck(size int64) files.Check { return &check{f: f, size: size, h: sha256.New()} }
